/**
 * A planned flow as the planning screens show it: an intention, never a fact (ADR-015). Its
 * amount is always positive; `direction` carries the sign.
 */
import type { Money } from './money';
import type { Recurrence } from './recurrence';

/** The three directions a planned flow can move money in, in the order the form offers them. */
export const DIRECTIONS = ['INFLOW', 'OUTFLOW', 'INVESTMENT'] as const;

/** One of the three directions (ADR-015). */
export type Direction = (typeof DIRECTIONS)[number];

/** The words shown for each direction on a flow's row, such as its `StateBadge`. */
export const DIRECTION_LABELS: Readonly<Record<Direction, string>> = {
    INFLOW: 'In',
    OUTFLOW: 'Out',
    INVESTMENT: 'Investment',
};

/** The words offered for each direction in the plan-flow form's Direction select. */
export const DIRECTION_OPTION_LABELS: Readonly<Record<Direction, string>> = {
    INFLOW: 'Money in',
    OUTFLOW: 'Money out',
    INVESTMENT: 'Into investments',
};

/** The four lifecycle statuses a planned flow moves through (mirrors `TransactionState`). */
export type PlanStatus = 'PLANNED' | 'COMMITTED' | 'REALISED' | 'CANCELLED';

/**
 * Where a planned flow has got to (ADR-028: a discriminated object on the wire).
 *
 * Each state carries exactly what it has: a planned flow has no date, a committed or realised one
 * has the date it got there, and a cancelled one also has the reason.
 */
export type PlanState =
    | { readonly status: 'PLANNED' }
    | { readonly status: 'COMMITTED'; readonly on: string }
    | { readonly status: 'REALISED'; readonly on: string }
    | { readonly status: 'CANCELLED'; readonly on: string; readonly reason: string };

/** A recorded planned flow. */
export interface PlannedFlow {
    readonly id: string;
    readonly description: string;
    /** Always positive; `direction` carries the sign (ADR-015). Never negated on this client. */
    readonly amount: Money;
    readonly direction: Direction;
    /** An ISO `YYYY-MM-DD` date. */
    readonly startsOn: string;
    readonly recurrence: Recurrence;
    readonly state: PlanState;
}

/** What planning a flow asks for. Identity is generated by the ledger, never sent (ADR-028). */
export interface PlanFlowInput {
    readonly description: string;
    /** Always positive; sent exactly as typed and never negated (ADR-015). */
    readonly amount: Money;
    readonly direction: Direction;
    /** An ISO `YYYY-MM-DD` date. */
    readonly startsOn: string;
    readonly recurrence: Recurrence;
}
