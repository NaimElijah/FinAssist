/**
 * A scenario as the planning screens show it: a named strategy of planned flows plus a growth
 * assumption (ADR-016). No arithmetic: the growth rate stays the string the ledger sent, or the
 * owner typed, and is never converted (ADR-029).
 */
import type { Currency } from './money';

/** A defined scenario. `flows` are plan ids; the do-nothing baseline has none. */
export interface Scenario {
    readonly id: string;
    readonly name: string;
    readonly currency: Currency;
    /** The ids of the planned flows this scenario assumes, in the ledger's order. */
    readonly flows: readonly string[];
    /** A decimal string exactly as received, such as `"0.005"`. Never parsed or converted. */
    readonly growthRatePerStep: string;
}

/** What defining a scenario asks for. Identity is generated by the ledger, never sent (ADR-028). */
export interface DefineScenarioInput {
    readonly name: string;
    readonly currency: Currency;
    /** Plan ids, each already in `currency`; the ledger checks both. May be empty (a baseline). */
    readonly flows: readonly string[];
    /** A decimal string, sent exactly as typed and never converted (ADR-029). */
    readonly growthRatePerStep: string;
}
