/**
 * A budget as the budgeting screens show it: a period, a currency and a limit per category.
 */
import type { Currency, Money } from './money';
import type { BudgetPeriod } from './period';

/** One category's spending limit. */
export interface CategoryLimit {
    readonly category: string;
    readonly limit: Money;
}

/** A defined budget, with its limits sorted by category and its total derived by the ledger. */
export interface Budget {
    readonly id: string;
    readonly period: BudgetPeriod;
    readonly currency: Currency;
    readonly limits: readonly CategoryLimit[];
    /** The sum of every limit, derived by the ledger and never computed here (ADR-029). */
    readonly total: Money;
}

/** What defining a budget asks for. Identity is generated by the ledger, never sent (ADR-028). */
export interface DefineBudgetInput {
    readonly period: BudgetPeriod;
    readonly currency: Currency;
    /** At least one limit, each in `currency`; the ledger checks both (ADR-011). */
    readonly limits: readonly CategoryLimit[];
}
