/**
 * An account as the accounting screens know it, in the ledger's own words.
 */
import type { Currency } from './money';

/** The five accounting types, in the order the form offers them. */
export const ACCOUNT_TYPES = ['ASSET', 'LIABILITY', 'INCOME', 'EXPENSE', 'EQUITY'] as const;

/** One of the five accounting types (ADR-011). */
export type AccountType = (typeof ACCOUNT_TYPES)[number];

/** The words a person reads for each accounting type. The wire's upper-case names are not those. */
export const ACCOUNT_TYPE_LABELS: Readonly<Record<AccountType, string>> = {
    ASSET: 'Asset',
    LIABILITY: 'Liability',
    INCOME: 'Income',
    EXPENSE: 'Expense',
    EQUITY: 'Equity',
};

/** An open account. It holds no balance: a balance is derived from entries and read separately. */
export interface Account {
    readonly id: string;
    readonly name: string;
    readonly type: AccountType;
    readonly currency: Currency;
}

/** What opening an account asks for. Identity is generated by the ledger, never sent (ADR-028). */
export interface OpenAccountInput {
    readonly name: string;
    readonly type: AccountType;
    readonly currency: Currency;
}
