/**
 * A transaction as the accounting screens show it: what happened, the entries it posted, and
 * where it has got to in its lifecycle.
 */
import type { Money } from './money';

/**
 * Where a transaction has got to (ADR-028: a discriminated object on the wire).
 *
 * Each state carries exactly what it has: a pending transaction has no date, a cleared or
 * reconciled one has the date it got there, and a voided one also has the reason.
 */
export type TransactionState =
    | { readonly status: 'PENDING' }
    | { readonly status: 'CLEARED'; readonly on: string }
    | { readonly status: 'RECONCILED'; readonly on: string }
    | { readonly status: 'VOIDED'; readonly on: string; readonly reason: string };

/** The four lifecycle statuses. */
export type TransactionStatus = TransactionState['status'];

/** One posting against one account. Signed, because double entry balances (ADR-011). */
export interface Entry {
    /** The id of the account posted to. */
    readonly account: string;
    readonly amount: Money;
}

/** A recorded transaction. Its entries sum to zero; the browser never checks or computes that. */
export interface Transaction {
    readonly id: string;
    /** An ISO `YYYY-MM-DD` date. */
    readonly occurredOn: string;
    readonly description: string;
    readonly entries: readonly Entry[];
    readonly state: TransactionState;
}

/** What recording a transaction by hand asks for. Identity is generated by the ledger. */
export interface RecordTransactionInput {
    /** An ISO `YYYY-MM-DD` date. */
    readonly occurredOn: string;
    readonly description: string;
    /** At least two entries, summing to zero in one currency; the ledger checks both (ADR-011). */
    readonly entries: readonly Entry[];
}

/** One entry row's debit/credit pair failed to map to a signed amount. */
export interface EntryRowError {
    readonly message: string;
}

/**
 * Map one entry row's debit and credit strings to the signed amount ADR-011's `Entry` carries: a
 * positive amount is a debit, so a credit is sent negative.
 *
 * No arithmetic ever touches the digits (ADR-029): a credit's amount is the debit string with a
 * leading `-` added, after any leading `-` the owner already typed is stripped first, so a credit
 * typed with its own sign is never doubled into `"--250.00"`.
 *
 * @param debit - the debit field's string, or `''` when left empty.
 * @param credit - the credit field's string, or `''` when left empty.
 * @returns the signed amount string, or an `EntryRowError` when both or neither side is filled.
 */
export function entryRowAmount(debit: string, credit: string): string | EntryRowError {
    const hasDebit = debit !== '';
    const hasCredit = credit !== '';
    if (hasDebit === hasCredit) {
        return { message: 'Enter a debit or a credit' };
    }
    if (hasDebit) {
        return debit;
    }
    return `-${credit.startsWith('-') ? credit.slice(1) : credit}`;
}
